; =================================================================
; 扩展磁盘读取函数 (INT 13h AH=42h)
; 输入:
;    EAX = LBA起始地址 (32位)
;    CX  = 待读取扇区数
;    EDI = 目标内存地址 (例如 0x9000:0x0000 处的 Loader)
; =================================================================
rd_disk_m_16:
    pushad

    ; 1. 构造磁盘地址包 (DAP) 在栈中
    ; DAP 结构 (16字节):
    ; [0] 1字节: 数据包大小 (常为 0x10)
    ; [1] 1字节: 保留 (0)
    ; [2] 2字节: 读取扇区数
    ; [4] 4字节: 内存目标地址 (偏移:段)
    ; [8] 8字节: LBA起始地址
    
    push dword 0        ; LBA 地址的高 32 位 (通常为 0)
    push eax            ; LBA 地址的低 32 位 (由 EAX 输入)
    
    ; 处理目标地址 EDI (逻辑地址需拆分为 段:偏移)
    ; 这里假设传入的是平坦物理地址，我们简单处理为 0000:EDI
    push edi            ; 目标偏移地址
    push word 0x0000    ; 目标段地址 (DS 默认为 0)
    
    push cx             ; 读取扇区数 (由 CX 输入)
    push word 0x0010    ; 数据包大小 10h 和 保留位 00h
    
    ; 2. 调用 BIOS 中断
    mov si, sp          ; DS:SI 指向栈中的 DAP
    mov dl, [BOOT_DRIVE] ; 驱动器号 (通常 MBR 开始时从 DL 获取，比如 0x80)
    mov ah, 0x42        ; 扩展读取功能号
    int 0x13
    
    jc .error           ; 如果进位标志置位，说明读取失败

    ; 3. 清理栈并返回
    add sp, 16          ; 恢复栈指针 (清理 DAP)
    popad
    ret

.error:
    ; 读取失败处理
    mov ax, 0x4c00
    int 0x21            ; 或者直接停机 hlt
    
; 数据段定义
BOOT_DRIVE: db 0x80     ; 默认第一个硬盘，实际应在程序开始时保存 DL